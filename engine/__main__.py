"""Usage: python -m engine build

Writes every card in a dark and a light variant to profile/assets/ and
regenerates profile/README.md to point at them.
"""

import hashlib
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

from .cards import CARDS
from .theme import THEMES

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "profile" / "assets"
README = ROOT / "profile" / "README.md"

# Organization profile READMEs don't resolve relative image paths, so links are absolute.
# raw.githubusercontent.com caches files for 5 minutes and ignores query strings, so the
# content hash goes into the file name: every version gets a fresh URL.
RAW = "https://raw.githubusercontent.com/gravisapp/.github/main/profile/assets"

ALT = {"hero": "Gravis — a new way to train at home. In development for iOS and Android."}


def picture(name: str, versions: dict[str, str]) -> str:
    def url(mode: str) -> str:
        return f"{RAW}/{name}-{mode}-{versions[mode]}.svg"

    return (
        "<picture>\n"
        f'  <source media="(prefers-color-scheme: dark)" srcset="{url("dark")}">\n'
        f'  <img src="{url("light")}" alt="{ALT[name]}" width="100%">\n'
        "</picture>\n"
    )


def build() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for stale in OUT.glob("*.svg"):
        stale.unlink()
    pictures = []
    for name, render in CARDS.items():
        versions = {}
        for mode, theme in THEMES.items():
            svg = render(theme)
            # Browsers render <img> SVG as strict XML and silently show nothing if it's malformed.
            ET.fromstring(svg)
            versions[mode] = hashlib.sha1(svg.encode()).hexdigest()[:8]
            (OUT / f"{name}-{mode}-{versions[mode]}.svg").write_text(svg, encoding="utf-8", newline="\n")
        pictures.append(picture(name, versions))
    README.write_text(
        "<!-- Generated by `python -m engine build`; edit engine/ instead. -->\n\n" + "\n".join(pictures),
        encoding="utf-8",
        newline="\n",
    )
    print(f"built {len(CARDS) * len(THEMES)} svg files and README -> {OUT.parent}")


if __name__ == "__main__":
    if sys.argv[1:] != ["build"]:
        sys.exit(__doc__)
    build()
